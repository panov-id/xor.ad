#!/usr/bin/env bash
# Экраны двух витрин — одно описание в двух местах.
#
#   scripts/check-screens-mirror.sh
#
# Зачем. Продукт описан не в гейте, а в экранах витрин, и описан дважды: файлы
# 00–20 у sosed.place и neighbro.place обязаны совпадать дословно. Проверял это
# никто: парность сверяет RU против EN внутри репозитория, а витрину против
# витрины — ничто. Замер 02.09.2026: двадцать один экран, различий ноль везде,
# кроме двух брендовых файлов. То есть правило соблюдалось руками — ровно тот
# случай, который однажды тихо перестаёт соблюдаться, потому что правку внесли
# в один репозиторий и забыли про второй.
#
# Два файла отличаются по существу и это решение, а не расхождение:
#   01-splash-screen  — имя витрины на заставке;
#   15-legal-documents — юридическое лицо, адреса и число языковых версий.
# Им разрешено различие, но только такое, которое исчезает при замене имён брендов
# и чисел на заглушки: разошедшийся абзац про механику остаётся видимым и там.
# Число здесь не придирка — витрины переведены на разное количество языков (17 и
# 10, замер 28.08.2026), и первый же прогон этих ворот нашёл именно эту пару строк.
#
# Коды выхода: 0 — сошлось; 1 — расхождение; 2 — нет репозитория витрины;
# 3 — сверять было нечего (ни одного экрана не нашлось).
set -uo pipefail

GROUP="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
A="$GROUP/sosed.place/docs"
B="$GROUP/neighbro.place/docs"
for d in "$A" "$B"; do
  [ -d "$d" ] || { echo "нет каталога экранов: $d" >&2; exit 2; }
done

BRAND_WORDS='sosed|neighbro|Сосед|соседи|Neighbro|SOSED|NEIGHBRO'
checked=0; bad=0; brandly=0

for path in "$A"/[0-2][0-9]-*.md; do
  [ -e "$path" ] || continue
  name="$(basename "$path")"
  twin="$B/$name"
  checked=$((checked + 1))
  if [ ! -f "$twin" ]; then
    bad=$((bad + 1)); printf '  ✗ %s — есть у одной витрины, нет у другой\n' "$name"; continue
  fi
  if diff -q "$path" "$twin" >/dev/null; then continue; fi

  case "$name" in
    01-splash-screen_*|15-legal-documents_*)
      # Обезличиваем обе стороны и сверяем снова: то, что осталось разным после
      # замены брендов и чисел, — расхождение по существу.
      norm() { sed -E "s/($BRAND_WORDS)/BRAND/g; s/[0-9]+/N/g" "$1"; }
      off="$(diff <(norm "$path") <(norm "$twin") | grep '^[<>]' || true)"
      if [ -n "$off" ]; then
        bad=$((bad + 1))
        printf '  ✗ %s — расхождение не про бренд и не про число:\n' "$name"
        printf '%s\n' "$off" | head -4 | sed 's/^/      /'
      else
        brandly=$((brandly + 1))
      fi
      ;;
    *)
      bad=$((bad + 1))
      printf '  ✗ %s — витрины разошлись на %s строк(ах)\n' \
        "$name" "$(diff "$path" "$twin" | grep -c '^[<>]')"
      ;;
  esac
done

if [ "$checked" = 0 ]; then
  echo "ни одного экрана не найдено — сверять было нечего"
  exit 3
fi
if [ "$bad" -gt 0 ]; then
  echo "экранов сверено: $checked — РАСХОЖДЕНИЙ: $bad"
  exit 1
fi
echo "экранов сверено: $checked (брендовых различий: $brandly) — витрины говорят одно и то же"
