#!/usr/bin/env python3
# The games' mini boards for the web, from the same drawing the sheets use
# (adaptive-sheets.py board_body), so a sheet and the screen cannot drift.
#
#   python3 scripts/design/export-game-art.py      # writes web/src/ui/gameArt.ts
#
# Colours become CSS: the lines are var(--gi) (the ink of the game's tile, set by
# GameArt.tsx), the tile var(--gt), the accent and danger the theme's; the light
# piece is the kit's constant paper and the dark one its ink, white and black in every theme
# as on the sheets (panel/design/kit/tokens.css).
import importlib.util
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
spec = importlib.util.spec_from_file_location("sheets", os.path.join(HERE, "adaptive-sheets.py"))
sheets = importlib.util.module_from_spec(spec)
spec.loader.exec_module(sheets)

art = {}
for gi, game in enumerate(sheets.GAMES):
    gid = game[0]
    # board_body reads the brightness of its colours, so it gets hex stand-ins
    # (a dark ink, a bright accent — the common case) and the CSS goes in after.
    marks = {"#0a0b0c": "var(--gi)", "#f0e1d2": "var(--accent)", "#0c0b0a": "var(--danger)", "#ffffff": "var(--paper)", "#1c140d": "var(--ink)"}
    body = sheets.board_body(gid, "#0a0b0c", "#ffffff", "#f0e1d2", "#0c0b0a", "#1c140d")
    for mark, css in marks.items():
        body = body.replace(mark, css)
    assert "#0a0b0c" not in body and "#f0e1d2" not in body
    art[gid] = {"tile": gi % 4 + 1, "body": body.replace('"BG"', '"var(--gt)"')}

out = os.path.join(ROOT, "web", "src", "ui", "gameArt.ts")
with open(out, "w") as f:
    f.write("// Generated by scripts/design/export-game-art.py from the sheets' drawing\n")
    f.write("// (scripts/design/adaptive-sheets.py board_body). Do not edit: rerun the script.\n\n")
    f.write("export const GAME_ART: Record<string, { tile: number; body: string }> = ")
    f.write(json.dumps(art, ensure_ascii=False, indent=2))
    f.write(";\n")
print(f"{len(art)} games -> {os.path.relpath(out, ROOT)}")

# The eight sticker reactions (owner 13.10.2026), from the same STICKERS the sheets draw:
# id (what travels), the 24-grid glyph, and the tile it sits on.
stickers = []
for i, (sid, _word, path) in enumerate(sheets.STICKERS):
    stickers.append({"id": sid, "tile": i % 4 + 1, "glyph": path.replace('"#ffffff"', '"var(--paper)"')})
out = os.path.join(ROOT, "web", "src", "ui", "stickerArt.ts")
with open(out, "w") as f:
    f.write("// Generated by scripts/design/export-game-art.py from the sheets' STICKERS\n")
    f.write("// (scripts/design/adaptive-sheets.py). Do not edit: rerun the script.\n\n")
    f.write("export const STICKER_ART: Array<{ id: string; tile: number; glyph: string }> = ")
    f.write(json.dumps(stickers, ensure_ascii=False, indent=2))
    f.write(";\n")
print(f"{len(stickers)} stickers -> {os.path.relpath(out, ROOT)}")
