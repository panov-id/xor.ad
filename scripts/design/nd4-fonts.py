#!/usr/bin/env python3
"""Fonts of the newdesign4 archive, taken out of its mockups into own files.

Every mockup HTML embeds its faces as base64 woff2 in @font-face. This collects the faces of all
24 files (deduplicated by content), writes each to app/tokens/nd4-fonts/<family>-<weight>-<n>.woff2
and app/tokens/nd4-fonts.gen.css with one @font-face per file. A face embedded twice under the same
family and weight is a subset; its unicode-range is read from its own cmap (fontTools), so the
browser picks the subset that has the glyph. Licence: the faces are OFL (Golos Text, Source Serif 4,
Lora, Literata). Run inside Docker with fonttools and brotli; prints "faces N of M written".
"""
import base64
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "docs/newdesign4/kit/sosed-design-2026-10-29/screens"
OUT_DIR = ROOT / "app/tokens/nd4-fonts"
OUT_CSS = ROOT / "app/tokens/nd4-fonts.gen.css"
FACE = re.compile(r"@font-face\{font-family:'([^']+)';font-weight:(\d+);src:url\(data:font/woff2;base64,([^)]+)\)")


def faces(src: Path = SRC) -> dict:
    """(family, weight) -> list of distinct woff2 bytes, in first-seen order."""
    out: dict = {}
    for f in sorted(src.glob("*.html")):
        for fam, w, b64 in FACE.findall(f.read_text(encoding="utf-8")):
            data = base64.b64decode(b64)
            lst = out.setdefault((fam, int(w)), [])
            if all(hashlib.sha256(d).digest() != hashlib.sha256(data).digest() for d in lst):
                lst.append(data)
    return out


def ranges(codepoints: list[int]) -> str:
    cps = sorted(codepoints)
    spans, start, prev = [], cps[0], cps[0]
    for c in cps[1:] + [None]:
        if c is not None and c == prev + 1:
            prev = c
            continue
        spans.append(f"U+{start:04X}" if start == prev else f"U+{start:04X}-{prev:04X}")
        if c is not None:
            start = prev = c
    return ", ".join(spans)


def cmap_of(data: bytes) -> list[int]:
    import io
    from fontTools.ttLib import TTFont
    return list(TTFont(io.BytesIO(data)).getBestCmap().keys())


def build(src: Path = SRC, out_dir: Path = OUT_DIR) -> tuple[str, dict]:
    found = faces(src)
    out_dir.mkdir(parents=True, exist_ok=True)
    blocks, files = [], {}
    for (fam, w), datas in sorted(found.items()):
        slug = fam.lower().replace(" ", "-")
        for n, data in enumerate(datas):
            name = f"{slug}-{w}-{n}.woff2"
            files[name] = data
            rng = f"\n  unicode-range: {ranges(cmap_of(data))};" if len(datas) > 1 else ""
            blocks.append(f'@font-face {{\n  font-family: "{fam}";\n  font-style: normal;\n  font-weight: {w};\n'
                          f'  font-display: swap;\n  src: url("./nd4-fonts/{name}") format("woff2");{rng}\n}}\n')
    head = "/* generated by scripts/design/nd4-fonts.py from docs/newdesign4 mockups; do not edit. OFL faces. */\n"
    return head + "".join(blocks), files


def main() -> int:
    css, files = build()
    if not files:
        print("ERROR: no @font-face found in", SRC)
        return 1
    for name, data in files.items():
        (OUT_DIR / name).write_bytes(data)
    OUT_CSS.write_text(css, encoding="utf-8")
    print(f"faces {len(files)} of {len(files)} written; families {sorted({n.rsplit('-', 2)[0] for n in files})}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
