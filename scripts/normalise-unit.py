#!/usr/bin/env python3
"""Единицы двух языков — к одной записи.

    ... | normalise-unit.py            строки «единица» → нормализованная
    ... | normalise-unit.py --pairs    строки «значение<TAB>единица» → пара
    normalise-unit.py --forms <ед>     все формы этой единицы, по строке на форму

«128 символов» и «128 characters» — одно и то же обязательство, записанное в двух
половинах. Считать их порознь значит удваивать каждый предел и получать покрытие,
где половина пар — отражение другой половины.
"""
import sys

# Падежи перечислены полностью, а не «основными формами»: первая версия знала
# «символов» и не знала «символами», и покрытие честно объявляло их разными
# единицами — в списке непокрытого рядом стояли «символах 256» и «chars 256».
UNITS = {
    'chars': ('символ', 'символа', 'символов', 'символами', 'символах', 'символом',
              'символе', 'символы', 'character', 'characters'),
    'bytes': ('байт', 'байта', 'байтов', 'байтами', 'байтах', 'байты', 'byte', 'bytes'),
    'm': ('м', 'метр', 'метра', 'метров', 'метрах', 'метрами', 'метры', 'метрам',
          'm', 'metre', 'metres', 'meter', 'meters'),
    'km': ('км', 'km'),
    's': ('сек', 'секунд', 'секунда', 'секунды', 'секунду', 'секундами', 'секундах', 'секундам',
          'second', 'seconds'),
    'min': ('мин', 'минут', 'минута', 'минуты', 'минуту', 'минутами', 'минутах', 'минутам',
            'minute', 'minutes'),
    'h': ('час', 'часа', 'часов', 'часами', 'часах', 'часы', 'часам', 'hour', 'hours'),
    'd': ('день', 'дня', 'дней', 'днями', 'днях', 'дни', 'дням', 'суток', 'сутки', 'сутках', 'суткам',
          'day', 'days'),
    'KB': ('КБ', 'KB'),
    'MB': ('МБ', 'MB'),
    'graphemes': ('графем', 'графема', 'графемы', 'графемами', 'графемах', 'графемам',
                  'grapheme', 'graphemes'),
}
LOOKUP = {form.lower(): name for name, forms in UNITS.items() for form in forms}


def normalise(unit):
    return LOOKUP.get(unit.strip().lower(), unit.strip())


# Обратный режим: по единице — все её формы. Нужен воротам пределов, чтобы у
# малого числа требовать единицу рядом. Без него «20» ищется как голый токен и
# находится где угодно: в chat_RU.md «20» встречается 30 раз, «1» — 40, и два
# несуществующих факта («короткий срок стола», «средний срок стола») числились
# действующими, пока их не нашла панель ревью 04.09.2026.
if '--forms' in sys.argv[1:]:
    wanted = normalise(sys.argv[sys.argv.index('--forms') + 1])
    for form in UNITS.get(wanted, ()):
        print(form)
    sys.exit(0)

pairs = '--pairs' in sys.argv[1:]
with_place = '--pairs-with-place' in sys.argv[1:]
for line in sys.stdin:
    line = line.rstrip('\n')
    if not line:
        continue
    if with_place:
        value, unit, place = (line.split('\t') + ['', '', ''])[:3]
        print(f'{value.strip()}\t{normalise(unit)}\t{place}')
    elif pairs:
        value, _, unit = line.partition('\t')
        print(f'{value.strip()}\t{normalise(unit)}')
    else:
        print(normalise(line))
