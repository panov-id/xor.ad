#!/usr/bin/env python3
"""Map of the 283 archive screens: family, app file, generated or hand, colors -> tokens.
Usage: python3 -I scripts/design/nd4-map.py [--check]"""
import csv, difflib, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
KIT = "docs/newdesign4/kit/sosed-design-2026-10-29"
SHOT = "kypros-phone"
THRESHOLD = 0.9
THEMES = "app/tokens/nd4-themes.gen.css"
OUT = {"EN": "docs/newdesign4/MAP_EN.md", "RU": "docs/newdesign4/MAP_RU.md"}
HEAD = "generated by scripts/design/nd4-map.py from " + KIT

COLOR = re.compile(r"#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b|rgba?\([^)]*\)")
DATA = re.compile(r"url\((['\"]?)data:.*?\1\)", re.S)
NUM = re.compile(r"-?\d+(?:\.\d+)?")


def read(p):
    with open(os.path.join(ROOT, p), encoding="utf-8") as f:
        return f.read()


def blocks(html):
    out = []
    for part in html.split('<div class="scr"')[1:]:
        part = part.split('<div class="item">')[0]
        out.append(DATA.sub("url()", '<div class="scr"' + part))
    return out


def norm_color(c):
    c = c.lower().replace(" ", "")
    if c.startswith("#") and len(c) == 4:
        c = "#" + "".join(ch * 2 for ch in c[1:])
    m = re.match(r"rgba?\((\d+),(\d+),(\d+)(?:,([\d.]+))?\)$", c)
    if m:
        r, g, b, a = m.groups()
        if a is None or float(a) == 1:
            return "#%02x%02x%02x" % (int(r), int(g), int(b))
        return "rgba(%s,%s,%s,%s)" % (r, g, b, ("%g" % float(a)))
    return c


def skeleton(b):
    # token list (tags, style declarations, text runs): difflib on 9k-char strings is too slow
    return re.findall(r"[^;<>\"]+", NUM.sub("0", COLOR.sub("C", b)))


def tokens():
    css = read(THEMES)
    m = re.search(r':root\[data-theme="limestone"\]\[data-time="day"\]\s*\{(.*?)\}', css, re.S)
    res = {}
    for name, val in re.findall(r"(--[\w-]+):\s*([^;]+);", m.group(1)):
        for c in COLOR.findall(val) if not val.strip().startswith(("linear", "radial", "color-mix")) else []:
            res.setdefault(norm_color(c), name)
    return res


def app_files():
    res = []
    for d, _, fs in os.walk(os.path.join(ROOT, "app/src")):
        for f in sorted(fs):
            if f.endswith((".ts", ".tsx")) and ".test." not in f:
                p = os.path.join(d, f)
                res.append((os.path.relpath(p, ROOT), open(p, encoding="utf-8").read()))
    return sorted(res)


def read_header(first):
    """The first line of a *.gen.tsx -> (whole screens, parts of screens), or None when it is not cut from the archive."""
    m = re.match(r"// generated from docs/newdesign4/\S+ (screens? .*?) by scripts/", first)
    if not m:
        return None
    fam = re.search(r"\(family [\w-]+: ([\d, ]+)\)", m[1])
    if fam:
        return {int(x) for x in re.findall(r"\d+", fam[1])}, set()
    return set(), {int(x) for x in re.findall(r"\d+", re.sub(r"\([^)]*\)", "", m[1]))}


def gen_headers(files):
    """screen number -> (whole or part, its file), the phone's file first; whole wins over part."""
    res = {}
    order = sorted(files, key=lambda f: (0 if "kypros-phone.html" in f[1].split("\n", 1)[0] else 1, f[0]))
    for path, text in order:
        got = read_header(text.split("\n", 1)[0]) if path.endswith(".gen.tsx") else None
        if got:
            for n in got[0]:
                if res.get(n, ("part",))[0] != "whole":
                    res[n] = ("whole", path)
            for n in got[1]:
                res.setdefault(n, ("part", path))
    return res


def build():
    rows = list(csv.reader(read(KIT + "/screens.csv").splitlines()))[1:]
    ids = [(int(r[0]), r[1], r[2], r[3]) for r in rows]
    count = {}
    for n in os.listdir(os.path.join(ROOT, KIT, "screens")):
        count[n] = read(KIT + "/screens/" + n).count('<div class="scr"')
    bl = blocks(read(KIT + "/screens/%s.html" % SHOT))
    assert len(bl) == len(ids), (len(bl), len(ids))
    sk = [skeleton(b) for b in bl]
    # families
    base_of, bases, fam = [], [], {}
    sms = {}
    for i, s in enumerate(sk):
        found = None
        for j in bases:
            sm = sms[j]
            sm.set_seq1(s)
            if sm.real_quick_ratio() >= THRESHOLD and sm.quick_ratio() >= THRESHOLD and sm.ratio() >= THRESHOLD:
                found = j
                break
        if found is None:
            bases.append(i)
            sms[i] = difflib.SequenceMatcher(None, "", sk[i], autojunk=False)
            found = i
        base_of.append(found)
        fam.setdefault(found, []).append(i)
    # app files: a generated file's first line says what it holds (panel 02.11): the family's numbers are whole screens,
    # any other number a part cut out of that screen. Only a named screen is credited, not its neighbours in a family.
    files = app_files()
    named = gen_headers(files)
    appf, kind_of = {}, {}
    for i, (n, sid, _, _) in enumerate(ids):
        if n in named:
            kind_of[i], appf[i] = named[n]
            continue
        # a hand-made screen names its id as a string; i18n.ts holds words, a bare word («me», «chat») is not a screen
        pat = re.compile(r"""["'`]%s["'`]""" % re.escape(sid))
        for path, text in files:
            if ".gen." not in path and not path.endswith("i18n.ts") and pat.search(text):
                kind_of[i], appf[i] = "hand", path
                break
    gen_of = {i: k != "hand" for i, k in kind_of.items()}
    # colors
    tok = tokens()
    percol, scol = {}, []
    for i, b in enumerate(bl):
        cs = sorted(set(norm_color(c) for c in COLOR.findall(b)))
        scol.append(cs)
        for c in cs:
            percol.setdefault(c, []).append(i)
    return dict(ids=ids, count=count, bl=bl, base_of=base_of, bases=bases, fam=fam,
                appf=appf, gen_of=gen_of, kind_of=kind_of, tok=tok, scol=scol, percol=percol)


def fmt_range(nums):
    nums = sorted(nums)
    out, s, p = [], nums[0], nums[0]
    for x in nums[1:] + [None]:
        if x is not None and x == p + 1:
            p = x; continue
        out.append(str(s) if s == p else "%d..%d" % (s, p))
        if x is not None: s = p = x
    return ", ".join(out)


L = {
    "EN": dict(title="Sosed archive screens map", fam="Families", col="Colors of %s", scr="Screens",
               intro="Screens: %d. Families (difflib ratio >= %s on skeleton, colors and numbers masked): %d. Screens with an app file: %d of %d. Ready used of %d: whole screens %d, parts of screens %d (first lines of *.gen.tsx).",
               cnt="Every archive file holds %d screens in the order of screens.csv.",
               fh="| Base № | Screens | Count | Base id | App file |", ch="| Color | Token (limestone day) | Screens |",
               sh="| № | id | Family (base №) | App file | Generated or hand | Colors | With token | No token |",
               gen="generated", part="generated part", hand="hand", none="none", notok="no token", tokn="Colors mapped to a token: %d of %d."),
    "RU": dict(title="Карта экранов архива sosed", fam="Семейства", col="Цвета %s", scr="Экраны",
               intro="Экранов: %d. Семейств (difflib ratio >= %s по скелету, цвета и числа замаскированы): %d. Экранов с файлом приложения: %d из %d. Ready used из %d: целых экранов %d, частей экранов %d (первые строки *.gen.tsx).",
               cnt="Каждый файл архива содержит %d экранов в порядке screens.csv.",
               fh="| № базы | Экраны | Число | id базы | Файл приложения |", ch="| Цвет | Токен (limestone day) | Экранов |",
               sh="| № | id | Семейство (№ базы) | Файл приложения | Сгенерирован или вручную | Цветов | С токеном | Без токена |",
               gen="сгенерирован", part="сгенерирована часть", hand="вручную", none="none", notok="no token", tokn="Цветов с токеном: %d из %d."),
}


def render(d, lang):
    t = L[lang]
    ids, appf, gen_of, tok = d["ids"], d["appf"], d["gen_of"], d["tok"]
    n = len(ids)
    kinds = list(d["kind_of"].values())
    o = [HEAD, "", "# " + t["title"], ""]
    o.append(t["intro"] % (n, THRESHOLD, len(d["fam"]), len(appf), n, n, kinds.count("whole"), kinds.count("part")))
    nfiles = sorted(set(d["count"].values()))
    o += ["", t["cnt"] % nfiles[0] + " (%d files)" % len(d["count"]) if len(nfiles) == 1 else "counts differ: %s" % nfiles, ""]
    o += ["## " + t["fam"], "", t["fh"], "|---|---|---|---|---|"]
    for j, mem in sorted(d["fam"].items()):
        files = sorted(set(appf[i] for i in mem if i in appf))
        o.append("| %d | %s | %d | %s | %s |" % (ids[j][0], fmt_range([ids[i][0] for i in mem]), len(mem),
                                               ids[j][1], ", ".join(files) or t["none"]))
    o += ["", "## " + t["col"] % SHOT, ""]
    mapped = sum(1 for c in d["percol"] if c in tok)
    o += [t["tokn"] % (mapped, len(d["percol"])), "", t["ch"], "|---|---|---|"]
    for c, mem in sorted(d["percol"].items(), key=lambda kv: (-len(kv[1]), kv[0])):
        o.append("| %s | %s | %d |" % (c, tok.get(c, t["notok"]), len(mem)))
    o += ["", "## " + t["scr"], "", t["sh"], "|---|---|---|---|---|---|---|---|"]
    for i, (num, sid, _, _) in enumerate(ids):
        cs = d["scol"][i]
        k = sum(1 for c in cs if c in tok)
        f = appf.get(i)
        kind = t["none"] if f is None else {"whole": t["gen"], "part": t["part"], "hand": t["hand"]}[d["kind_of"][i]]
        o.append("| %d | %s | %d | %s | %s | %d | %d | %d |" % (num, sid, ids[d["base_of"][i]][0], f or t["none"], kind, len(cs), k, len(cs) - k))
    return "\n".join(o) + "\n"


def main():
    d = build()
    outs = {k: render(d, k) for k in OUT}
    if "--check" in sys.argv:
        bad = [p for k, p in OUT.items() if not os.path.exists(os.path.join(ROOT, p)) or read(p) != outs[k]]
        if bad:
            print("DIFFER: " + ", ".join(bad)); return 1
        print("OK: files match a fresh render"); return 0
    for k, p in OUT.items():
        with open(os.path.join(ROOT, p), "w", encoding="utf-8") as f:
            f.write(outs[k])
    print("written", ", ".join(OUT.values()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
